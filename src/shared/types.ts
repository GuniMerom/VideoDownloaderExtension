// Shared TypeScript types for the Video Downloader Extension

export interface VideoStream {
  url: string;
  quality: string;
  resolution?: string;
  bandwidth?: number;
  codec?: string;
  type: 'video' | 'audio' | 'muxed';
  format?: string;
  fileSize?: number;
  frameRate?: string;
  groupId?: string;
}

export type DownloadReadiness =
  | 'ready_with_muxed_output'
  | 'ready_with_separate_audio_needing_merge'
  | 'ready_video_only'
  | 'unsupported_drm_or_unmergeable';

export interface SubtitleTrack {
  url: string;
  language: string;
  label?: string;
  format: 'vtt' | 'srt' | 'ttml' | 'unknown';
  isAutoGenerated?: boolean;
}

export interface VideoInfo {
  id: string;
  title: string;
  thumbnail?: string;
  duration?: number;
  provider: string;
  pageUrl: string;
  streams: VideoStream[];
  subtitles: SubtitleTrack[];
  downloadReadiness?: DownloadReadiness;
  downloadWarnings?: string[];
  metadata?: Record<string, unknown>;
}

export interface DetectedVideo {
  id: string;
  type: 'html5' | 'iframe' | 'stream';
  url: string;
  title?: string;
  thumbnail?: string;
  provider: string;
  tabId?: number;
  frameId?: number;
}

/** A detected video that has been (or is being) analyzed for download options. */
export interface AnalyzedVideo {
  detected: DetectedVideo;
  status: 'pending' | 'analyzing' | 'ready' | 'error';
  videoInfo?: VideoInfo;    // Populated when status === 'ready'
  error?: string;           // Populated when status === 'error'
}

export interface DownloadTask {
  id: string;
  videoInfo: VideoInfo;
  selectedStream: VideoStream;
  audioStream?: VideoStream;
  subtitleTracks?: SubtitleTrack[];
  status: 'pending' | 'downloading' | 'muxing' | 'complete' | 'error';
  progress: number;
  error?: string;
  outputFilename?: string;
  completionMessage?: string;
  startedAt: number;
  completedAt?: number;
}

export interface ExtensionSettings {
  preferredQuality: 'best' | '1080p' | '720p' | '480p' | '360p';
  autoDetect: boolean;
  downloadSubtitles: boolean;
  showNotifications: boolean;
  enabledProviders: string[];
}

export const DEFAULT_SETTINGS: ExtensionSettings = {
  preferredQuality: 'best',
  autoDetect: true,
  downloadSubtitles: true,
  showNotifications: true,
  enabledProviders: [],
};
