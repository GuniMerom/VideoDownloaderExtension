function renderTopicEntries(entries: TopicEntry[]): string {
  if (!entries.length) return '_None extracted._';
  return entries.map((entry) => {
    const evidence = entry.evidence.length ? `\nEvidence: ${entry.evidence.join(' | ')}` : '';
    return `- **${entry.name}**: ${entry.detail}${evidence}`;
  }).join('\n');
}

function renderRecipeBlocks(recipes: RecipeEntry[]): string {
  if (!recipes.length) return '_No recipe blocks extracted._';
  return recipes.map((recipe) => {
    const sections = [
      `### ${recipe.title}`,
      recipe.context ? recipe.context : '',
      recipe.ingredients.length ? `Ingredients:\n${recipe.ingredients.map((value) => `- ${value}`).join('\n')}` : '',
      recipe.quantities.length ? `Quantities Stated:\n${recipe.quantities.map((value) => `- ${value}`).join('\n')}` : '',
      recipe.steps.length ? `Steps:\n${recipe.steps.map((value, index) => `${index + 1}. ${value}`).join('\n')}` : '',
      recipe.techniqueNotes.length ? `Technique Notes:\n${recipe.techniqueNotes.map((value) => `- ${value}`).join('\n')}` : '',
      recipe.platingNotes.length ? `Plating / Serving Notes:\n${recipe.platingNotes.map((value) => `- ${value}`).join('\n')}` : '',
      recipe.substitutions.length ? `Substitutions / Variations:\n${recipe.substitutions.map((value) => `- ${value}`).join('\n')}` : '',
      recipe.evidence.length ? `Evidence: ${recipe.evidence.join(' | ')}` : '',
    ].filter(Boolean);
    return sections.join('\n\n');
  }).join('\n\n');
}

function renderStringList(values: string[]): string {
  if (!values.length) return '_None recorded._';
  return values.map((value) => `- ${value}`).join('\n');
}

