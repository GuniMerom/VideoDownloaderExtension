function buildLessonSignature(lesson: LessonNode, options: CliOptions): Promise<string> {
  return Promise.all([
    statSignature(lesson.videoPath),
    ...lesson.subtitlePaths.map((subtitlePath) => statSignature(subtitlePath)),
  ]).then((parts) => sha256(JSON.stringify({
    lessonKey: lesson.lessonKey,
    files: parts,
    model: options.model,
    transcriptionModel: options.transcriptionModel,
    language: options.language,
    withVisuals: options.withVisuals,
    version: SUMMARY_VERSION,
  })));
}

async function summarizeLesson(
  lesson: LessonNode,
  options: CliOptions,
  manifest: SummaryManifest,
  manifestPath: string,
): Promise<LessonManifestEntry> {
  const sourceSignature = await buildLessonSignature(lesson, options);
  const existing = manifest.lessons.find((entry) => entry.lessonKey === lesson.lessonKey);
  const canSkip = !options.force
    && existing?.sourceSignature === sourceSignature
    && await pathExists(lesson.summaryJsonPath)
    && await pathExists(lesson.summaryMarkdownPath);

  if (canSkip) {
    const skipped: LessonManifestEntry = {
      lessonKey: lesson.lessonKey,
      lessonTitle: lesson.title,
      chapterOrder: lesson.chapterOrder,
      lessonOrder: lesson.lessonOrder,
      sourceSignature,
      summaryJsonPath: lesson.summaryJsonPath,
      summaryMarkdownPath: lesson.summaryMarkdownPath,
      sourceType: existing?.sourceType,
      status: 'skipped',
      updatedAt: new Date().toISOString(),
    };
    manifest.lessons = manifest.lessons.filter((entry) => entry.lessonKey !== lesson.lessonKey).concat(skipped);
    await writeManifest(manifestPath, manifest);
    return skipped;
  }

  if (options.dryRun) {
    const dryRun: LessonManifestEntry = {
      lessonKey: lesson.lessonKey,
      lessonTitle: lesson.title,
      chapterOrder: lesson.chapterOrder,
      lessonOrder: lesson.lessonOrder,
      sourceSignature,
      summaryJsonPath: lesson.summaryJsonPath,
      summaryMarkdownPath: lesson.summaryMarkdownPath,
      status: 'dry-run',
      updatedAt: new Date().toISOString(),
    };
    manifest.lessons = manifest.lessons.filter((entry) => entry.lessonKey !== lesson.lessonKey).concat(dryRun);
    await writeManifest(manifestPath, manifest);
    return dryRun;
  }

  try {
    const source = await buildLessonSource(lesson, options);
    const chunks = chunkCues(source);
    const primaryLanguage = detectPrimaryLanguage(source.cues.map((cue) => cue.text).join(' '));
    const chunkSummaries: ChunkSummary[] = [];

    for (const chunk of chunks) {
      chunkSummaries.push(await summarizeChunk(chunk, lesson, primaryLanguage, options));
    }

    const merged = await mergeLessonChunks(chunkSummaries, lesson, source, options);
    const markdown = renderLessonMarkdown(merged);

    await ensureDir(path.dirname(lesson.summaryJsonPath));
    await ensureDir(path.dirname(lesson.summaryMarkdownPath));
    await writeFile(lesson.summaryJsonPath, JSON.stringify(merged, null, 2), 'utf8');
    await writeFile(lesson.summaryMarkdownPath, markdown, 'utf8');

    const success: LessonManifestEntry = {
      lessonKey: lesson.lessonKey,
      lessonTitle: lesson.title,
      chapterOrder: lesson.chapterOrder,
      lessonOrder: lesson.lessonOrder,
      sourceSignature,
      summaryJsonPath: lesson.summaryJsonPath,
      summaryMarkdownPath: lesson.summaryMarkdownPath,
      sourceType: source.sourceType,
      status: 'success',
      updatedAt: new Date().toISOString(),
    };
    manifest.lessons = manifest.lessons.filter((entry) => entry.lessonKey !== lesson.lessonKey).concat(success);
    await writeManifest(manifestPath, manifest);
    return success;
  } catch (error) {
    const failed: LessonManifestEntry = {
      lessonKey: lesson.lessonKey,
      lessonTitle: lesson.title,
      chapterOrder: lesson.chapterOrder,
      lessonOrder: lesson.lessonOrder,
      sourceSignature,
      summaryJsonPath: lesson.summaryJsonPath,
      summaryMarkdownPath: lesson.summaryMarkdownPath,
      status: 'failed',
      updatedAt: new Date().toISOString(),
      error: stringifyError(error),
    };
    manifest.lessons = manifest.lessons.filter((entry) => entry.lessonKey !== lesson.lessonKey).concat(failed);
    await writeManifest(manifestPath, manifest);
    return failed;
  }
}

async function loadLessonSummaries(course: CourseNode): Promise<LessonSummaryData[]> {
  const summaries: LessonSummaryData[] = [];
  for (const chapter of course.chapters) {
    for (const lesson of chapter.lessons) {
      if (await pathExists(lesson.summaryJsonPath)) {
        summaries.push(JSON.parse(await readFile(lesson.summaryJsonPath, 'utf8')) as LessonSummaryData);
      }
    }
  }
  return summaries;
}

