function uniqueTopicMap(entries: Array<{ lesson: LessonSummaryData; items: TopicEntry[] }>): Map<string, { detail: string[]; evidence: string[]; lessons: string[] }> {
  const map = new Map<string, { detail: string[]; evidence: string[]; lessons: string[] }>();
  for (const entry of entries) {
    for (const item of entry.items) {
      const key = item.name.toLowerCase();
      if (!map.has(key)) {
        map.set(key, { detail: [], evidence: [], lessons: [] });
      }
      const target = map.get(key)!;
      if (item.detail && !target.detail.includes(item.detail)) {
        target.detail.push(item.detail);
      }
      for (const evidence of item.evidence) {
        if (!target.evidence.includes(evidence)) {
          target.evidence.push(evidence);
        }
      }
      const lessonRef = `${formatIndex(entry.lesson.metadata.chapterOrder)}.${formatIndex(entry.lesson.metadata.lessonOrder)} ${entry.lesson.metadata.lessonTitle}`;
      if (!target.lessons.includes(lessonRef)) {
        target.lessons.push(lessonRef);
      }
    }
  }
  return map;
}

function renderIngredientsMarkdown(course: CourseNode, lessons: LessonSummaryData[]): string {
  const map = uniqueTopicMap(lessons.map((lesson) => ({ lesson, items: lesson.ingredientNotes })));
  const sections = Array.from(map.entries())
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, data]) => [
      `## ${name}`,
      data.detail.length ? data.detail.map((value) => `- ${value}`).join('\n') : '_No detail recorded._',
      data.lessons.length ? `Lessons: ${data.lessons.join('; ')}` : '',
      data.evidence.length ? `Evidence: ${data.evidence.join(' | ')}` : '',
    ].filter(Boolean).join('\n\n'));
  return [`# ${course.title} - Ingredients Reference`, '', ...sections].join('\n\n');
}

