function normalizeText(value: string | null | undefined): string {
  return (value ?? '').replace(/\s+/g, ' ').trim();
}

function sanitizePathSegment(value: string, fallback: string): string {
  const sanitized = normalizeText(value)
    .replace(INVALID_FILENAME_CHARS, '_')
    .replace(/\s+/g, ' ')
    .trim();
  return sanitized || fallback;
}

function formatIndex(value: number): string {
  return String(value).padStart(2, '0');
}

function stringifyError(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

function sha256(input: string): string {
  return createHash('sha256').update(input).digest('hex');
}

function timestampFromSeconds(totalSeconds: number): string {
  const safeSeconds = Math.max(0, Math.floor(totalSeconds));
  const hours = Math.floor(safeSeconds / 3600);
  const minutes = Math.floor((safeSeconds % 3600) / 60);
  const seconds = safeSeconds % 60;
  return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
}

function detectPrimaryLanguage(text: string): string {
  const hebrewCount = (text.match(/[\u0590-\u05FF]/g) || []).length;
  const latinCount = (text.match(/[A-Za-z]/g) || []).length;
  if (hebrewCount > latinCount * 0.25) {
    return 'he';
  }
  return 'en';
}

function parsePositiveInteger(name: string, value: string | undefined): number | undefined {
  if (value === undefined) return undefined;
  const parsed = Number.parseInt(value, 10);
  if (!Number.isFinite(parsed) || parsed < 1) {
    throw new Error(`--${name} must be a positive integer.`);
  }
  return parsed;
}

function parseArgs(argv: string[]): CliOptions {
  const flags = new Set<string>();
  const values = new Map<string, string>();

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (!argument.startsWith('--')) {
      throw new Error(`Unexpected argument: ${argument}`);
    }

    const [rawKey, inlineValue] = argument.slice(2).split('=', 2);
    if (rawKey === 'force' || rawKey === 'dry-run' || rawKey === 'with-visuals') {
      flags.add(rawKey);
      continue;
    }

    const value = inlineValue ?? argv[index + 1];
    if (!value || value.startsWith('--')) {
      throw new Error(`Missing value for --${rawKey}.`);
    }

    values.set(rawKey, value);
    if (!inlineValue) {
      index += 1;
    }
  }

  const courseRoot = values.get('course-root');
  if (!courseRoot) {
    throw new Error('Missing required --course-root.');
  }

  const chapter = parsePositiveInteger('chapter', values.get('chapter'));
  const lesson = parsePositiveInteger('lesson', values.get('lesson'));
  if (lesson && !chapter) {
    throw new Error('--lesson can only be used together with --chapter.');
  }

  const languageValue = (values.get('language') || 'bilingual') as SummaryLanguage;
  if (!['bilingual', 'match', 'english'].includes(languageValue)) {
    throw new Error('--language must be one of: bilingual, match, english.');
  }

  return {
    courseRoot: path.resolve(courseRoot),
    chapter,
    lesson,
    force: flags.has('force'),
    dryRun: flags.has('dry-run'),
    model: values.get('model') || DEFAULT_SUMMARY_MODEL,
    transcriptionModel: values.get('transcription-model') || DEFAULT_TRANSCRIPTION_MODEL,
    language: languageValue,
    withVisuals: flags.has('with-visuals'),
  };
}

async function pathExists(targetPath: string): Promise<boolean> {
  try {
    await access(targetPath);
    return true;
  } catch {
    return false;
  }
}

async function ensureDir(targetPath: string): Promise<void> {
  await mkdir(targetPath, { recursive: true });
}

async function statSignature(targetPath: string): Promise<string> {
  try {
    const fileStat = await stat(targetPath);
    return `${targetPath}|${fileStat.size}|${fileStat.mtimeMs}`;
  } catch {
    return `${targetPath}|missing`;
  }
}

async function ensureFfmpegAvailable(): Promise<void> {
  if (process.env.FFMPEG_PATH && existsSync(process.env.FFMPEG_PATH)) {
    ffmpegBinary = process.env.FFMPEG_PATH;
  } else {
    const locator = process.platform === 'win32'
      ? spawnSync('where.exe', ['ffmpeg.exe'], { encoding: 'utf8' })
      : spawnSync('which', ['ffmpeg'], { encoding: 'utf8' });
    const discoveredPath = locator.status === 0
      ? locator.stdout.split(/\r?\n/).map((line) => line.trim()).find(Boolean)
      : undefined;
    if (discoveredPath) {
      ffmpegBinary = discoveredPath;
    } else {
      const candidate = path.join(
        process.env.LOCALAPPDATA || '',
        'Microsoft',
        'WinGet',
        'Packages',
        'Gyan.FFmpeg_Microsoft.Winget.Source_8wekyb3d8bbwe',
        'ffmpeg-8.1-full_build',
        'bin',
        'ffmpeg.exe',
      );
      if (candidate && existsSync(candidate)) {
        ffmpegBinary = candidate;
      }
    }
  }

  const result = spawnSync(ffmpegBinary, ['-version'], { stdio: 'ignore' });
  if (result.error || result.status !== 0) {
    throw new Error('ffmpeg is not installed or not on PATH. Install ffmpeg, then rerun the summarizer.');
  }
}

async function runFfmpeg(args: string[], label: string): Promise<void> {
  await new Promise<void>((resolve, reject) => {
    const child = spawn(ffmpegBinary, ['-nostdin', ...args], {
      stdio: ['ignore', 'pipe', 'pipe'],
    });

    let stderr = '';
    child.stderr.on('data', (chunk: Buffer) => {
      stderr += chunk.toString();
    });

    child.on('error', (error) => {
      reject(new Error(`ffmpeg ${label} failed to start: ${error.message}`));
    });

    child.on('close', (code) => {
      if (code === 0) {
        resolve();
        return;
      }
      reject(new Error(`ffmpeg ${label} failed with exit code ${code}: ${stderr.trim()}`));
    });
  });
}

async function getMediaDurationSeconds(filePath: string): Promise<number> {
  const duration = await new Promise<number>((resolve, reject) => {
    const child = spawn(ffmpegBinary.replace(/ffmpeg(\.exe)?$/i, 'ffprobe$1'), [
      '-v', 'error',
      '-show_entries', 'format=duration',
      '-of', 'default=nw=1:nk=1',
      filePath,
    ], {
      stdio: ['ignore', 'pipe', 'pipe'],
    });

    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (chunk: Buffer) => {
      stdout += chunk.toString();
    });
    child.stderr.on('data', (chunk: Buffer) => {
      stderr += chunk.toString();
    });
    child.on('error', (error) => {
      reject(new Error(`ffprobe failed to start for ${path.basename(filePath)}: ${error.message}`));
    });
    child.on('close', (code) => {
      if (code !== 0) {
        reject(new Error(`ffprobe failed for ${path.basename(filePath)}: ${stderr.trim()}`));
        return;
      }
      const parsed = Number.parseFloat(stdout.trim());
      if (!Number.isFinite(parsed)) {
        reject(new Error(`ffprobe returned an invalid duration for ${path.basename(filePath)}.`));
        return;
      }
      resolve(parsed);
    });
  });

  return duration;
}

async function readManifest(manifestPath: string, options: CliOptions, courseRoot: string, courseTitle: string, summaryRoot: string): Promise<SummaryManifest> {
  if (await pathExists(manifestPath)) {
    try {
      const parsed = JSON.parse(await readFile(manifestPath, 'utf8')) as SummaryManifest;
      return parsed;
    } catch {
      // Fall back to a fresh manifest if the existing file is malformed.
    }
  }

  return {
    version: SUMMARY_VERSION,
    generatedAt: new Date().toISOString(),
    courseRoot,
    courseTitle,
    summaryRoot,
    options: {
      model: options.model,
      transcriptionModel: options.transcriptionModel,
      language: options.language,
      withVisuals: options.withVisuals,
    },
    lessons: [],
    documents: [],
  };
}

async function writeManifest(manifestPath: string, manifest: SummaryManifest): Promise<void> {
  manifest.generatedAt = new Date().toISOString();
  await ensureDir(path.dirname(manifestPath));
  await writeFile(manifestPath, JSON.stringify(manifest, null, 2), 'utf8');
}

async function discoverCourse(courseRoot: string, options: CliOptions): Promise<CourseNode> {
  const courseStats = await stat(courseRoot).catch(() => null);
  if (!courseStats?.isDirectory()) {
    throw new Error(`Course root was not found or is not a directory: ${courseRoot}`);
  }

  const entries = await readdir(courseRoot, { withFileTypes: true });
  const chapterDirs = entries
    .filter((entry) => entry.isDirectory() && /^(\d+)\s*-\s*/.test(entry.name))
    .map((entry) => {
      const match = entry.name.match(/^(\d+)\s*-\s*(.+)$/);
      return {
        order: match ? Number.parseInt(match[1], 10) : 999,
        title: sanitizePathSegment(match?.[2] || entry.name, entry.name),
        dir: path.join(courseRoot, entry.name),
      };
    })
    .sort((left, right) => left.order - right.order || left.title.localeCompare(right.title));

  const selectedChapters = options.chapter
    ? chapterDirs.filter((chapter) => chapter.order === options.chapter)
    : chapterDirs;

  if (options.chapter && !selectedChapters.length) {
    throw new Error(`Chapter ${options.chapter} was not found under ${courseRoot}.`);
  }

  const summaryRoot = path.join(courseRoot, '_Summaries');
  const chapters: ChapterNode[] = [];

  for (const chapter of selectedChapters) {
    const chapterEntries = await readdir(chapter.dir, { withFileTypes: true });
    const lessons = chapterEntries
      .filter((entry) => entry.isFile() && /\.mp4$/i.test(entry.name))
      .map((entry) => {
        const match = entry.name.match(/^(\d+)\s*-\s*(.+)\.mp4$/i);
        const lessonOrder = match ? Number.parseInt(match[1], 10) : 999;
        const lessonTitle = sanitizePathSegment(match?.[2] || entry.name.replace(/\.mp4$/i, ''), `Lesson ${lessonOrder}`);
        const videoPath = path.join(chapter.dir, entry.name);
        const lessonBase = entry.name.replace(/\.mp4$/i, '');
        const subtitlePaths = chapterEntries
          .filter((candidate) => candidate.isFile() && candidate.name.startsWith(`${lessonBase}.`) && /\.(vtt|srt)$/i.test(candidate.name))
          .map((candidate) => path.join(chapter.dir, candidate.name))
          .sort((left, right) => left.localeCompare(right));
        const lessonKey = `${formatIndex(chapter.order)}-${formatIndex(lessonOrder)}-${sanitizePathSegment(lessonTitle, 'lesson')}`;
        return {
          courseTitle: sanitizePathSegment(path.basename(courseRoot), path.basename(courseRoot)),
          chapterOrder: chapter.order,
          chapterTitle: chapter.title,
          lessonOrder,
          title: lessonTitle,
          videoPath,
          subtitlePaths,
          lessonKey,
          summaryJsonPath: path.join(summaryRoot, 'Intermediate', 'Lessons', `${lessonKey}.json`),
          summaryMarkdownPath: path.join(summaryRoot, 'Lessons', `${lessonKey}.md`),
        } as LessonNode;
      })
      .sort((left, right) => left.lessonOrder - right.lessonOrder || left.title.localeCompare(right.title));

    const selectedLessons = options.lesson
      ? lessons.filter((lesson) => lesson.lessonOrder === options.lesson)
      : lessons;

    if (options.lesson && options.chapter === chapter.order && !selectedLessons.length) {
      throw new Error(`Lesson ${options.lesson} was not found inside chapter ${chapter.order}.`);
    }

    if (selectedLessons.length > 0) {
      chapters.push({
        order: chapter.order,
        title: chapter.title,
        dir: chapter.dir,
        lessons: selectedLessons,
      });
    }
  }

  if (!chapters.length) {
    throw new Error(`No chapter folders with lesson videos were found under ${courseRoot}.`);
  }

  return {
    title: sanitizePathSegment(path.basename(courseRoot), path.basename(courseRoot)),
    courseRoot,
    summaryRoot,
    chapters,
  };
}

function parseTimestamp(value: string): number {
  const normalized = value.trim().replace(',', '.');
  const parts = normalized.split(':').map((part) => part.trim());
  if (parts.length < 2 || parts.length > 3) return Number.NaN;

  const secondsPart = Number.parseFloat(parts[parts.length - 1]);
  const minutesPart = Number.parseInt(parts[parts.length - 2] || '0', 10);
  const hoursPart = parts.length === 3 ? Number.parseInt(parts[0] || '0', 10) : 0;
  if (![secondsPart, minutesPart, hoursPart].every((number) => Number.isFinite(number))) {
    return Number.NaN;
  }
  return hoursPart * 3600 + minutesPart * 60 + secondsPart;
}

function parseVttContent(content: string): SourceCue[] {
  const lines = content.replace(/\r/g, '').split('\n');
  const cues: SourceCue[] = [];
  let index = 0;

  while (index < lines.length) {
    const line = lines[index].trim();
    if (!line || /^WEBVTT/i.test(line) || /^NOTE/i.test(line)) {
      index += 1;
      continue;
    }

    const timingLine = line.includes('-->') ? line : lines[index + 1]?.trim();
    if (!timingLine || !timingLine.includes('-->')) {
      index += 1;
      continue;
    }

    const [rawStart, rawEnd] = timingLine.split('-->').map((part) => part.trim().split(/\s+/)[0]);
    const startSeconds = parseTimestamp(rawStart);
    const endSeconds = parseTimestamp(rawEnd);
    if (!Number.isFinite(startSeconds) || !Number.isFinite(endSeconds)) {
      index += 1;
      continue;
    }

    const cueLines: string[] = [];
    index += line.includes('-->') ? 1 : 2;
    while (index < lines.length && lines[index].trim()) {
      cueLines.push(lines[index].trim().replace(/<[^>]+>/g, ''));
      index += 1;
    }

    const text = normalizeText(cueLines.join(' '));
    if (text) {
      cues.push({
        startSeconds,
        endSeconds,
        text,
        sourceType: 'subtitle',
      });
    }
    index += 1;
  }

  return cues;
}

function parseSrtContent(content: string): SourceCue[] {
  const blocks = content.replace(/\r/g, '').split('\n\n');
  const cues: SourceCue[] = [];

  for (const block of blocks) {
    const lines = block.split('\n').map((line) => line.trim()).filter(Boolean);
    if (lines.length < 2) continue;
    const timingLine = lines.find((line) => line.includes('-->'));
    if (!timingLine) continue;
    const [rawStart, rawEnd] = timingLine.split('-->').map((part) => part.trim().split(/\s+/)[0]);
    const startSeconds = parseTimestamp(rawStart);
    const endSeconds = parseTimestamp(rawEnd);
    if (!Number.isFinite(startSeconds) || !Number.isFinite(endSeconds)) continue;
    const text = normalizeText(lines.filter((line) => !line.includes('-->') && !/^\d+$/.test(line)).join(' '));
    if (!text) continue;
    cues.push({
      startSeconds,
      endSeconds,
      text,
      sourceType: 'subtitle',
    });
  }

  return cues;
}

async function loadBestSubtitleSource(subtitlePaths: string[]): Promise<LessonSource | null> {
  let best: LessonSource | null = null;

  for (const subtitlePath of subtitlePaths) {
    const content = await readFile(subtitlePath, 'utf8');
    const cues = /\.srt$/i.test(subtitlePath) ? parseSrtContent(content) : parseVttContent(content);
    const text = normalizeText(cues.map((cue) => cue.text).join(' '));
    if (!text) continue;
    const qualityNotes: string[] = [];
    const fileName = path.basename(subtitlePath).toLowerCase();
    if (fileName.includes('autogen') || fileName.includes('auto')) {
      qualityNotes.push('Subtitle filename suggests auto-generated captions.');
    }
    if (cues.length < 5) {
      qualityNotes.push('Very low cue count.');
    }
    if (text.length < 400) {
      qualityNotes.push('Very short subtitle text.');
    }

    const source: LessonSource = {
      sourceType: 'subtitle',
      subtitlePath,
      languageHint: detectPrimaryLanguage(text),
      autoGeneratedHint: qualityNotes.some((note) => note.toLowerCase().includes('auto-generated')),
      charCount: text.length,
      cueCount: cues.length,
      qualityNotes,
      cues,
    };

    if (!best || source.charCount > best.charCount) {
      best = source;
    }
  }

  return best;
}

function getOpenAiConfig() {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    throw new Error('OPENAI_API_KEY is required for non-dry-run summarization.');
  }
  return {
    apiKey,
    baseUrl: process.env.OPENAI_BASE_URL || 'https://api.openai.com/v1',
  };
}

function parseRetryDelayMs(response: Response, bodyText: string, attempt: number): number {
  const retryAfterHeader = response.headers.get('retry-after');
  if (retryAfterHeader) {
    const seconds = Number.parseFloat(retryAfterHeader);
    if (Number.isFinite(seconds) && seconds > 0) {
      return Math.ceil(seconds * 1000) + 1000;
    }
  }

  const messageMatch = bodyText.match(/Please try again in\s+([0-9.]+)s/i);
  if (messageMatch) {
    const seconds = Number.parseFloat(messageMatch[1]);
    if (Number.isFinite(seconds) && seconds > 0) {
      return Math.ceil(seconds * 1000) + 1000;
    }
  }

  return Math.min(120_000, 5_000 * 2 ** attempt);
}

async function openAiFetch(endpoint: string, init: RequestInit): Promise<Response> {
  const { apiKey, baseUrl } = getOpenAiConfig();

  for (let attempt = 0; attempt <= OPENAI_MAX_RETRIES; attempt += 1) {
    const headers = new Headers(init.headers || {});
    headers.set('Authorization', `Bearer ${apiKey}`);

    const response = await fetch(`${baseUrl}${endpoint}`, {
      ...init,
      headers,
    });

    if (response.ok) {
      return response;
    }

    const bodyText = await response.text();
    const isRateLimited = response.status === 429;
    if (!isRateLimited || attempt === OPENAI_MAX_RETRIES) {
      throw new Error(`OpenAI request failed: ${response.status} ${response.statusText} - ${bodyText}`);
    }

    const delayMs = parseRetryDelayMs(response, bodyText, attempt);
    console.warn(`OpenAI rate limit hit. Retrying in ${Math.ceil(delayMs / 1000)}s (attempt ${attempt + 1}/${OPENAI_MAX_RETRIES}).`);
    await sleep(delayMs);
  }

  throw new Error('OpenAI request failed after exhausting retries.');
}

