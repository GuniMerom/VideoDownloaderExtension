function renderRecipesMarkdown(course: CourseNode, lessons: LessonSummaryData[]): string {
  const recipeSections: string[] = [];
  for (const lesson of lessons) {
    for (const recipe of lesson.recipes) {
      recipeSections.push([
        `## ${recipe.title}`,
        `Lesson: ${formatIndex(lesson.metadata.chapterOrder)}.${formatIndex(lesson.metadata.lessonOrder)} ${lesson.metadata.lessonTitle}`,
        recipe.context || '',
        recipe.ingredients.length ? `Ingredients:\n${recipe.ingredients.map((value) => `- ${value}`).join('\n')}` : '',
        recipe.quantities.length ? `Quantities:\n${recipe.quantities.map((value) => `- ${value}`).join('\n')}` : '',
        recipe.steps.length ? `Steps:\n${recipe.steps.map((value, index) => `${index + 1}. ${value}`).join('\n')}` : '',
        recipe.techniqueNotes.length ? `Technique Notes:\n${recipe.techniqueNotes.map((value) => `- ${value}`).join('\n')}` : '',
        recipe.platingNotes.length ? `Plating Notes:\n${recipe.platingNotes.map((value) => `- ${value}`).join('\n')}` : '',
        recipe.substitutions.length ? `Substitutions:\n${recipe.substitutions.map((value) => `- ${value}`).join('\n')}` : '',
        recipe.evidence.length ? `Evidence: ${recipe.evidence.join(' | ')}` : '',
      ].filter(Boolean).join('\n\n'));
    }
  }
  return [`# ${course.title} - Recipes Reference`, '', recipeSections.join('\n\n') || '_No recipes extracted._'].join('\n\n');
}

async function generateHigherLevelOutputs(course: CourseNode, options: CliOptions, manifest: SummaryManifest, manifestPath: string): Promise<void> {
  const lessons = await loadLessonSummaries(course);
  if (!lessons.length) {
    return;
  }

  const chapterSummaries: Array<{ chapterOrder: number; chapterTitle: string; content: string }> = [];

  for (const chapter of course.chapters) {
    const chapterLessons = lessons.filter((lesson) => lesson.metadata.chapterOrder === chapter.order);
    if (!chapterLessons.length) continue;
    const signature = sha256(JSON.stringify(chapterLessons.map((lesson) => [lesson.metadata.lessonKey, lesson.source.charCount, lesson.metadata.primaryLanguage])));
    const targetPath = path.join(course.summaryRoot, 'Chapters', `${formatIndex(chapter.order)} - ${chapter.title}.md`);
    const content = options.dryRun
      ? `# ${chapter.title}\n\n_Dry run: chapter summary would be generated here._\n`
      : await generateChapterMarkdown(chapter, chapterLessons, options);
    await writeDocument(manifest, manifestPath, `chapter:${chapter.order}`, 'chapter', targetPath, signature, content, options.dryRun);
    chapterSummaries.push({
      chapterOrder: chapter.order,
      chapterTitle: chapter.title,
      content,
    });
  }

  const overviewSignature = sha256(JSON.stringify(chapterSummaries.map((chapter) => [chapter.chapterOrder, chapter.content.length])));
  const overviewContent = options.dryRun
    ? `# ${course.title} - Course Overview\n\n_Dry run: course overview would be generated here._\n`
    : await generateCourseOverviewMarkdown(course, chapterSummaries, options);
  await writeDocument(
    manifest,
    manifestPath,
    'course:overview',
    'course',
    path.join(course.summaryRoot, 'Course Overview.md'),
    overviewSignature,
    overviewContent,
    options.dryRun,
  );

  const ingredientsSignature = sha256(JSON.stringify(lessons.map((lesson) => [lesson.metadata.lessonKey, lesson.ingredientNotes.length])));
  const techniquesSignature = sha256(JSON.stringify(lessons.map((lesson) => [lesson.metadata.lessonKey, lesson.techniqueNotes.length])));
  const recipesSignature = sha256(JSON.stringify(lessons.map((lesson) => [lesson.metadata.lessonKey, lesson.recipes.length])));
  const glossarySignature = sha256(JSON.stringify(lessons.map((lesson) => [lesson.metadata.lessonKey, lesson.glossary.length])));

  await writeDocument(
    manifest,
    manifestPath,
    'reference:ingredients',
    'ingredients',
    path.join(course.summaryRoot, 'Reference', 'Ingredients.md'),
    ingredientsSignature,
    renderIngredientsMarkdown(course, lessons),
    options.dryRun,
  );
  await writeDocument(
    manifest,
    manifestPath,
    'reference:techniques',
    'techniques',
    path.join(course.summaryRoot, 'Reference', 'Techniques.md'),
    techniquesSignature,
    renderTechniquesMarkdown(course, lessons),
    options.dryRun,
  );
  await writeDocument(
    manifest,
    manifestPath,
    'reference:recipes',
    'recipes',
    path.join(course.summaryRoot, 'Reference', 'Recipes.md'),
    recipesSignature,
    renderRecipesMarkdown(course, lessons),
    options.dryRun,
  );
  await writeDocument(
    manifest,
    manifestPath,
    'reference:glossary',
    'glossary',
    path.join(course.summaryRoot, 'Reference', 'Glossary.md'),
    glossarySignature,
    renderGlossaryMarkdown(course, lessons),
    options.dryRun,
  );
}

async function runSummarizer(options: CliOptions): Promise<void> {
  const course = await discoverCourse(options.courseRoot, options);
  const manifestPath = path.join(course.summaryRoot, 'manifest.json');
  const manifest = await readManifest(manifestPath, options, course.courseRoot, course.title, course.summaryRoot);

  if (!options.dryRun) {
    await ensureFfmpegAvailable();
    getOpenAiConfig();
  }

  if (options.withVisuals) {
    console.warn('Visual enrichment is not implemented in v1 yet. Continuing with subtitles/audio only.');
  }

  console.log(`Course: ${course.title}`);
  console.log(`Course root: ${course.courseRoot}`);
  console.log(`Summary root: ${course.summaryRoot}`);
  console.log(`Chapters selected: ${course.chapters.length}`);
  console.log(`Lessons selected: ${course.chapters.reduce((count, chapter) => count + chapter.lessons.length, 0)}`);

  await writeManifest(manifestPath, manifest);

  for (const chapter of course.chapters) {
    console.log(`\nChapter ${formatIndex(chapter.order)} - ${chapter.title}`);
    for (const lesson of chapter.lessons) {
      console.log(`  Summarizing ${formatIndex(chapter.order)}.${formatIndex(lesson.lessonOrder)} ${lesson.title}`);
      const entry = await summarizeLesson(lesson, options, manifest, manifestPath);
      if (entry.status === 'failed') {
        console.error(`    Failed: ${entry.error || 'Unknown error'}`);
      } else if (entry.status === 'skipped') {
        console.log('    Skipped: summary outputs already match the current source.');
      } else if (entry.status === 'dry-run') {
        console.log('    Dry run: summary outputs would be created.');
      } else {
        console.log(`    Done: ${lesson.summaryMarkdownPath}`);
      }
    }
  }

  await generateHigherLevelOutputs(course, options, manifest, manifestPath);
  console.log('\nSummarization finished.');
  console.log(`Manifest: ${manifestPath}`);
}

async function main(): Promise<void> {
  if (process.argv.includes('--help')) {
    printUsage();
    return;
  }

  const options = parseArgs(process.argv.slice(2));
  await runSummarizer(options);
}

void main().catch((error) => {
  console.error(stringifyError(error));
  process.exitCode = 1;
});
