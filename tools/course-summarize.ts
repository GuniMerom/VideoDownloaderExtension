async function transcribeAudioSegments(segmentPaths: string[], options: CliOptions): Promise<SourceCue[]> {
  const cues: SourceCue[] = [];

  for (let index = 0; index < segmentPaths.length; index += 1) {
    const segmentPath = segmentPaths[index];
    const buffer = await readFile(segmentPath);
    const segmentDuration = await getMediaDurationSeconds(segmentPath);
    const formData = new FormData();
    formData.append('model', options.transcriptionModel);
    formData.append('response_format', 'json');
    formData.append('file', new Blob([buffer]), path.basename(segmentPath));

    const response = await openAiFetch('/audio/transcriptions', {
      method: 'POST',
      body: formData,
    });

    const payload = await response.json() as {
      text?: string;
    };

    const offset = index * AUDIO_SEGMENT_SECONDS;
    const text = normalizeText(payload.text);
    if (text) {
      cues.push({
        startSeconds: offset,
        endSeconds: offset + Math.max(1, Math.ceil(segmentDuration)),
        text,
        sourceType: 'transcript',
      });
    }
  }

  return cues;
}

async function transcribeLessonAudio(videoPath: string, options: CliOptions): Promise<LessonSource> {
  const tempRoot = await mkdtemp(path.join(tmpdir(), 'course-summarize-'));
  try {
    const segmentPattern = path.join(tempRoot, 'audio-%03d.mp3');
    await runFfmpeg([
      '-y',
      '-loglevel', 'error',
      '-i', videoPath,
      '-vn',
      '-ac', '1',
      '-ar', '16000',
      '-b:a', '48k',
      '-f', 'segment',
      '-segment_time', String(AUDIO_SEGMENT_SECONDS),
      segmentPattern,
    ], `audio segmentation for ${path.basename(videoPath)}`);

    const segmentPaths = (await readdir(tempRoot, { withFileTypes: true }))
      .filter((entry) => entry.isFile() && /\.mp3$/i.test(entry.name))
      .map((entry) => path.join(tempRoot, entry.name))
      .sort((left, right) => left.localeCompare(right));

    if (!segmentPaths.length) {
      throw new Error(`No audio segments were produced for ${videoPath}`);
    }

    const cues = await transcribeAudioSegments(segmentPaths, options);
    const text = normalizeText(cues.map((cue) => cue.text).join(' '));
    return {
      sourceType: 'transcript',
      transcriptSegments: segmentPaths.map((segmentPath) => path.basename(segmentPath)),
      languageHint: detectPrimaryLanguage(text),
      autoGeneratedHint: false,
      charCount: text.length,
      cueCount: cues.length,
      qualityNotes: ['Transcript was generated from lesson audio because no usable subtitles were found.'],
      cues,
    };
  } finally {
    await rm(tempRoot, { recursive: true, force: true });
  }
}

async function buildLessonSource(lesson: LessonNode, options: CliOptions): Promise<LessonSource> {
  const subtitleSource = await loadBestSubtitleSource(lesson.subtitlePaths);
  if (subtitleSource && subtitleSource.charCount >= 400) {
    return subtitleSource;
  }
  return transcribeLessonAudio(lesson.videoPath, options);
}

function chunkCues(source: LessonSource): PreparedChunk[] {
  const chunks: PreparedChunk[] = [];
  let current: SourceCue[] = [];
  let currentTextLength = 0;
  let chunkIndex = 1;

  const flush = (): void => {
    if (!current.length) return;
    chunks.push({
      index: chunkIndex,
      startSeconds: current[0].startSeconds,
      endSeconds: current[current.length - 1].endSeconds,
      sourceType: source.sourceType,
      text: normalizeText(current.map((cue) => `${timestampFromSeconds(cue.startSeconds)} ${cue.text}`).join('\n')),
      cueCount: current.length,
    });
    chunkIndex += 1;
    current = [];
    currentTextLength = 0;
  };

  for (const cue of source.cues) {
    const cueLength = cue.text.length;
    const currentDuration = current.length
      ? cue.endSeconds - current[0].startSeconds
      : 0;
    const shouldFlush = current.length > 0
      && (currentTextLength + cueLength > DEFAULT_CHUNK_CHAR_LIMIT || currentDuration > DEFAULT_CHUNK_DURATION_SECONDS);
    if (shouldFlush) {
      flush();
    }
    current.push(cue);
    currentTextLength += cueLength;
  }

  flush();
  return chunks;
}

